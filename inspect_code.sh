#!/bin/bash
# سكريبت خارجي لفحص كود Mirror Scorpion v2 وفهم هيكل الاستدعاء الحالي

echo "=================================================="
echo "🕵️‍♂️ بدء فحص واستكشاف الهيكل الحالي لكود Adham..."
echo "=================================================="

echo -e "\n[1] محتوى ملف main.dart الحالي (الـ 84 سطر لمعرفة الاستدعاءات والـ Imports):"
echo "--------------------------------------------------"
if [ -f "lib/main.dart" ]; then
    cat lib/main.dart
else
    echo "⚠️ ملف lib/main.dart غير موجود!"
fi

echo -e "\n--------------------------------------------------"
echo "[2] هيكل المجلدات الحالي داخل lib (لمعرفة مكان الكروت والخدمات):"
echo "--------------------------------------------------"
if [ -d "lib" ]; then
    find lib -maxdepth 3
else
    echo "⚠️ مجلد lib غير موجود بالأساس!"
fi

echo -e "\n--------------------------------------------------"
echo "[3] فحص ملف pubspec.yaml (لمعرفة المكتبات والأصوات المعتمدة):"
echo "--------------------------------------------------"
if [ -f "pubspec.yaml" ]; then
    grep -E "dependencies:|sdk:|flutter:|assets:" -A 10 pubspec.yaml
else
    echo "⚠️ ملف pubspec.yaml غير موجود في هذا المسار!"
fi

echo -e "\n=================================================="
echo "✅ انتهى الفحص. انسخ الناتج بالكامل في ردك القادم."
echo "=================================================="
