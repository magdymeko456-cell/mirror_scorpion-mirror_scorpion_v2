#!/usr/bin/env bash
set -euo pipefail

cd ~/mirror_scorpion/mirror_scorpion_v2

echo "══════════════════════════════════════════"
echo "  نقل الملفات للمجلد الرئيسي وتنظيف الداخلي"
echo "══════════════════════════════════════════"

# 1. نقل كل الملفات والمجلدات من المجلد الداخلي إلى المجلد الرئيسي الحالي
if [ -d "mirror_scorpion_v2" ]; then
    echo "جاري نقل الملفات بأمان..."
    cp -r mirror_scorpion_v2/* . 2>/dev/null || true
    cp -r mirror_scorpion_v2/.[!.]* . 2>/dev/null || true
    
    # 2. الآن بعد التأكد من النقل، مسح المجلد الداخلي تماماً وهو فارغ أو مكرر
    rm -rf mirror_scorpion_v2
    echo "✅ تم مسح المجلد الداخلي بنجاح بعد تأمين الملفات برة."
else
    echo "المجلد الداخلي غير موجود بالفعل."
fi

# 3. إعادة تهيئة الـ Git على الهيكل النظيف الجديد
git rm --cached -r . 2>/dev/null || true
git add .

echo "══════════════════════════════════════════"
echo "  الوضع الحالي للـ Git بعد التنظيف الفعلي:"
echo "══════════════════════════════════════════"
git status
