#!/bin/bash
echo "=========================================="
echo "🧹 سكريبت تنظيف محاولات البناء الفاشلة (المصحح) 🦂"
echo "=========================================="

echo "🔍 جاري البحث عن محاولات البناء الفاشلة (Failure)..."

# جلب معرفات المحاولات الفاشلة
FAILED_RUNS=$(gh run list --status failure --limit 1000 --json databaseId --jq '.[].databaseId')

if [ -z "$FAILED_RUNS" ]; then
    echo "✨ ممتاز يا صديقي! لا توجد محاولات بناء فاشلة حالياً."
    exit 0
fi

echo "🗑️ تم العثور على محاولات فاشلة، جاري الحذف الحقيقي الآن..."

for RUN_ID in $FAILED_RUNS; do
    echo "⏳ جاري حذف المحاولة رقم: $RUN_ID ..."
    # تمرير y لتأكيد الحذف التلقائي بدون فليجات وهمية
    echo "y" | gh run delete "$RUN_ID"
done

echo "=========================================="
echo "✅ تم تنظيف المستودع فعلياً الآن يا تامر!"
echo "=========================================="
