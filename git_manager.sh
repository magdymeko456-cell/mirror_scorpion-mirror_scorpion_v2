#!/bin/bash
# سكريبت خارجي لإدارة عمليات الرفع والتحقق من الهيكل

echo "=========================================="
echo "🦂 جاري التحقق من حالة المستودع والرفع..."
echo "=========================================="

# 1. محاولة الدفع بعد تحديث الرابط بالتوكن
echo "[1/2] جاري رفع التحديثات إلى GitHub..."
git push origin main

if [ $? -eq 0 ]; then
    echo "✅ تم الرفع بنجاح إلى المستودع الرئيسي!"
else
    echo "❌ فشل الرفع. يرجى التأكد من صحة الـ Token وصلاحياته (Repo permissions)."
fi

# 2. فحص سري للملفات الحالية لمعرفة ما تم كتابته
echo "------------------------------------------"
echo "[2/2] حالة الملفات الأساسية في المشروع:"
echo "------------------------------------------"
if [ -f "lib/main.dart" ]; then
    echo "✅ ملف lib/main.dart موجود."
    echo "عدد الأسطر الحالية في main.dart: $(wc -l < lib/main.dart)"
else
    echo "⚠️ تنبيه: ملف lib/main.dart غير موجود أو لم يتم إنشاؤه بالكامل!"
fi
